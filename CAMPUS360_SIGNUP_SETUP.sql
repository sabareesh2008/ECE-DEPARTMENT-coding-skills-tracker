create or replace function public.campus360_lookup_student(p_reg_no text)
returns table(reg_no text, full_name text, section text, leetcode_username text, claimed boolean)
language sql security definer set search_path = public
as $$
  select r.reg_no, r.full_name, r.section, r.leetcode_username, (r.claimed_by is not null)
  from public.campus360_student_roster r
  where r.reg_no = trim(p_reg_no)
  limit 1;
$$;
revoke all on function public.campus360_lookup_student(text) from public;
grant execute on function public.campus360_lookup_student(text) to anon, authenticated;

create or replace function public.campus360_handle_new_student()
returns trigger
language plpgsql security definer set search_path = public, auth
as $$
declare
  v_reg text;
  v_email text;
  v_name text;
  v_section text;
  v_lc text;
  v_claimed uuid;
  v_approved_email text;
begin
  v_reg := trim(coalesce(new.raw_user_meta_data->>'campus360_reg_no',''));
  if v_reg = '' or coalesce(new.raw_user_meta_data->>'signup_kind','') <> 'student' then
    return new;
  end if;
  v_email := lower(coalesce(new.email,''));
  select full_name, section, leetcode_username, claimed_by, approved_email
    into v_name, v_section, v_lc, v_claimed, v_approved_email
    from public.campus360_student_roster where reg_no = v_reg for update;
  if not found then raise exception 'Registration number is not present in the approved student roster.'; end if;
  if v_claimed is not null then raise exception 'This registration number is already claimed. Contact the administrator.'; end if;
  if v_approved_email is not null and lower(v_approved_email) <> v_email then
    raise exception 'Use the college email address registered with your college.';
  end if;
  update public.campus360_student_roster set claimed_by = new.id where reg_no = v_reg and claimed_by is null;
  if not found then raise exception 'This registration number was just claimed by another account.'; end if;
  insert into public.campus360_user_roles(user_id,role) values(new.id,'student')
    on conflict(user_id) do nothing;
  insert into public.campus360_student_profiles(auth_user_id,reg_no,full_name,college_email,section,leetcode_username)
    values(new.id,v_reg,v_name,v_email,v_section,v_lc)
    on conflict(auth_user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists campus360_auth_new_student on auth.users;
create trigger campus360_auth_new_student after insert on auth.users
for each row execute function public.campus360_handle_new_student();

