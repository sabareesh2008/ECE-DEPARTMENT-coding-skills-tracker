-- Campus360 self-sign-up / roster integration. Review and run ONLY in the Supabase project used by login.html.
-- Additive only: does not drop or rewrite existing CodeMetrix tables. Student roster seed comes from students.csv.
-- IMPORTANT: for production, add college-issued email addresses or invitation codes to the roster and validate them.

create table if not exists public.campus360_student_roster (
  reg_no text primary key,
  full_name text not null,
  section text,
  leetcode_username text,
  approved_email text,
  claimed_by uuid unique references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.campus360_user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('student','faculty','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.campus360_student_profiles (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid unique not null references auth.users(id) on delete cascade,
  reg_no text unique not null references public.campus360_student_roster(reg_no),
  full_name text not null,
  college_email text not null,
  section text,
  leetcode_username text,
  status text not null default 'active' check (status in ('pending','active','suspended')),
  created_at timestamptz not null default now()
);

