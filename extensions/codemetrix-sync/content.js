  // --- AI PROMPT & COMMENT SIGNATURE SCANNER ---
  function scanAiComments(code) {
    if (!code) return { hasPromptComments: false, flags: [] };

    const flags = [];

    // 1. Time/Space Complexity AI summary headers
    const complexityRegex = /\b(time\s*complexity|space\s*complexity|time\s*:\s*o\(|space\s*:\s*o\(|complexity\s*analysis|runtime\s*complexity)\b/i;
    if (complexityRegex.test(code)) {
      flags.push('AI Complexity Header');
    }

    // 2. Direct ChatGPT / AI Assistant signatures
    const aiBrandRegex = /\b(chatgpt|copilot|claude|gemini|openai|gpt-4|anthropic|generated by ai|ai solution)\b/i;
    if (aiBrandRegex.test(code)) {
      flags.push('AI Brand Signature');
    }

    // 3. Prompt structured response artifacts (e.g., "Approach:", "Algorithm:", "Step 1:")
    const promptStructureRegex = /\b(approach|algorithm|step\s*1|explanation|intuition|dry\s*run)\s*:/i;
    if (promptStructureRegex.test(code)) {
      flags.push('AI Prompt Structure Artifact');
    }

    // 4. Markdown code fences (e.g. ```java or ``` pasted into Monaco)
    const markdownRegex = /```(?:java|cpp|c\+\+|python|python3|javascript|c|go|rust)?/i;
    if (markdownRegex.test(code)) {
      flags.push('Markdown Code Fence');
    }

    // 5. Verbatim problem prompt echo comments
    const promptEchoRegex = /\/\*\s*(?:Problem\s*Statement|Leetcode\s*#\s*\d+|Given\s+an\s+array|You\s+are\s+given)/i;
    const pyPromptEchoRegex = /#\s*(?:Problem\s*Statement|Leetcode\s*#\s*\d+|Given\s+an\s+array|You\s+are\s+given)/i;
    if (promptEchoRegex.test(code) || pyPromptEchoRegex.test(code)) {
      flags.push('Problem Prompt Echo Header');
    }

    return {
      hasPromptComments: flags.length > 0,
      flags: flags
    };
  }

  // --- COMPOSITE PLAGIARISM RISK SCORING ---
  function calculatePlagiarismRisk(code, difficulty, timeSpentSeconds, keystrokes, pasted, numPastes, switches, aiScanResult) {
    let score = 0;
    const finalFlags = [...(aiScanResult?.flags || [])];
    const codeLen = (code || '').trim().length;
    const ratio = codeLen > 0 ? (keystrokes / codeLen) : (keystrokes > 0 ? 1 : 0);
    const hasAiComments = Boolean(aiScanResult?.hasPromptComments);
    const hasPasteAction = Boolean(pasted || numPastes > 0);

    // DIRECT 100% FLAGGING RULES:
    // Rule 1: Any paste with minimal typing (< 40 keystrokes) OR low typed ratio (<= 20%)
    if (hasPasteAction && (keystrokes < 40 || ratio <= 0.20)) {
      score = 98;
      finalFlags.push(`Direct Code Paste Detected (${keystrokes} keys typed / ${numPastes} pastes / ${Math.round(ratio * 100)}% typed)`);
    }

    // Rule 2: 0% to 15% typing ratio on any substantive code
    if (ratio <= 0.15 && codeLen > 20) {
      score = Math.max(score, 95);
      finalFlags.push(`Extreme Keystroke Deficit (${keystrokes} Keystrokes for ${codeLen} chars, ${Math.round(ratio * 100)}% typed)`);
    }

    // Rule 3: Direct paste with keystrokes < 60
    if (hasPasteAction && keystrokes < 60) {
      score = Math.max(score, 90);
      finalFlags.push(`Pasted Code Insertion (${numPastes} pastes, ${keystrokes} keystrokes)`);
    }

    // Rule 4: AI Prompt signature / comments
    if (hasAiComments) {
      score = Math.max(score, (hasPasteAction || ratio < 0.5) ? 98 : 85);
      finalFlags.push('AI Generated Solution Signature / Header Comments');
    }

    // Rule 5: Low keystrokes (< 15) regardless of anything
    if (keystrokes < 15) {
      score = Math.max(score, 95);
      finalFlags.push(`Unverified / Low Keystroke Count (${keystrokes} keys)`);
    }

    // Secondary accumulative checks
    if (score < 80) {
      if (hasPasteAction && ratio < 0.35) {
        score += 45;
        finalFlags.push(`High Paste Ratio (${Math.round(ratio * 100)}% typed)`);
      } else if (ratio < 0.30) {
        score += 35;
        finalFlags.push('Low Typing Activity');
      }

      if (timeSpentSeconds < 20) {
        score += 30;
        finalFlags.push('Instant Solve Time (<20s)');
      }

      if (switches >= 3 && hasPasteAction) {
        score += 20;
        finalFlags.push(`Tab Switching Pre-Paste (${switches} switches)`);
      }
    }

    score = Math.min(100, Math.max(0, score));

    let verdict = 'CLEAN';
    if (score >= 70 || (hasPasteAction && keystrokes < 40) || ratio <= 0.15) {
      verdict = 'FLAGGED';
    } else if (score >= 45 || (hasPasteAction && ratio < 0.40)) {
      verdict = 'SUSPICIOUS';
    } else if (score >= 20) {
      verdict = 'LOW_RISK';
    }

    return {
      score: score,
      verdict: verdict,
      keystrokeRatio: parseFloat(ratio.toFixed(2)),
      flags: finalFlags,
      hasPromptComments: hasAiComments
    };
  }

