  // --- TAB ACTIVE TIME & VISIBILITY TRACKER ---
  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState === 'hidden') {
      const elapsed = (Date.now() - lastActiveTimestamp) / 1000;
      if (elapsed > 0) {
        accumulatedActiveSeconds += elapsed;
      }
      tabSwitchCount++;
    } else if (document.visibilityState === 'visible') {
      lastActiveTimestamp = Date.now();
    }
  });

  function getTotalActiveSeconds() {
    let total = accumulatedActiveSeconds;
    if (document.visibilityState === 'visible') {
      const currentSession = (Date.now() - lastActiveTimestamp) / 1000;
      if (currentSession > 0) total += currentSession;
    }
    return Math.max(1, Math.round(total));
  }

